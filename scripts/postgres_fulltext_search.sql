/*
АНАЛИЗ ОГРАНИЧЕНИЙ ПОЛНОТЕКСТОВОГО ПОИСКА POSTGRESQL В НОВОСТНОМ АГРЕГАТОРЕ:

1. Просадка производительности записи (Write Amplification):
   - При массовом парсинге новостей (тысячи статей в минуту) обновление GIN-индекса
     создает огромную нагрузку на диск и WAL-журнал. В отличие от B-Tree, вставка 
     в GIN требует расщепления текста на десятки лексем и обновления инвертированных списков.
   - Требуется частый VACUUM для предотвращения разрастания (bloat) GIN-индекса.

2. Отсутствие нечеткого поиска (Fuzzy Search / Опечатки) "из коробки":
   - FTS в PostgreSQL ищет только точные стеммированные формы слов (через Snowball).
   - Если пользователь ввел поисковый запрос с опечаткой ("пстгрес" вместо "постгрес"),
     FTS ничего не найдет. Для исправления требуется подключать стороннее расширение 
     `pg_trgm` и вычислять расстояние Левенштейна, что на миллионах строк крайне медленно.

3. Проблема многоязычности (Multilingual News):
   - Новостной агрегатор собирает статьи на разных языках (русский, английский, смешанные термины).
   - В PostgreSQL функция to_tsvector требует жесткого указания конфигурации ('russian' или 'english').
   - Полноценное автоопределение языка для каждого документа требует внешних анализаторов.

4. Горизонтальное масштабирование:
   - В PostgreSQL поиск выполняется на центральном узле БД, потребляя ресурсы CPU/RAM,
     критичные для основных транзакций записи.
   - В архитектуре высоконагруженного агрегатора полнотекстовый поиск целесообразно выносить
     в распределенный специализированный поисковый движок (Elasticsearch / OpenSearch) 
     или использовать Atlas Search в документной модели MongoDB.
*/
